
public class Medicamento {

    String nome;
    String fabricante;
    double preco;
    int quantidade;
    String dosagem;

    public Medicamento(String nome, String fabricante,
                       double preco, int quantidade, String dosagem) {

        this.nome = nome;
        this.fabricante = fabricante;
        this.preco = preco;
        this.quantidade = quantidade;
        this.dosagem = dosagem;
    }
}





